"""Export: TorchScript, ONNX, INT8 dynamic-quantized, embedded C header. Usage: python export.py"""
import os
import numpy as np
import torch
import torch.nn as nn
from config import MAX_LEN, CHARS, ARM, ARM_CLASSES, SAFETY, INTENTS, LED, ARTIFACT, HEADER
from model import EdgeChemNet
from topics import TOPIC_IDS

OUT = [f"{ARTIFACT}.pt", f"{ARTIFACT}.onnx", f"{ARTIFACT}_quantized.pt", HEADER]


def kb(p): return f"{os.path.getsize(p)/1024:.0f} KB"


def c_array(name, arr, ctype):
    body = ",".join(str(x) for x in arr.flatten().tolist())
    return f"static const {ctype} {name}[{arr.size}] = {{{body}}};\n"


def write_header(net, path):
    L = ["/* Auto-generated by export.py. int8 per-tensor symmetric weights, fp32 biases/norms. */\n",
         "#pragma once\n#include <stdint.h>\n"]
    L.append(f"#define IQO_MAX_LEN {MAX_LEN}\n#define IQO_N_TOPICS {len(TOPIC_IDS)}\n")
    L.append(f'static const char IQO_CHARSET[] = "{CHARS}"; /* token id = index+2, 0=pad, 1=unk */\n')
    L.append("static const char* IQO_SAFETY[] = {%s};\n" % ",".join(f'"{s}"' for s in SAFETY))
    L.append("static const char* IQO_LED[] = {%s};\n" % ",".join(f'"{LED[s]}"' for s in SAFETY))
    L.append("static const char* IQO_INTENT[] = {%s};\n" % ",".join(f'"{s}"' for s in INTENTS))
    L.append("static const char* IQO_ARM_NAME[] = {%s};\n" % ",".join(f'"{s}"' for s in ARM_CLASSES))
    L.append("static const int16_t IQO_ARM_PAN_TILT_REACH[][3] = {%s};\n" % ",".join("{%d,%d,%d}" % ARM[s] for s in ARM_CLASSES))
    L.append("#define IQO_LCD_COLS 16\n")
    flash = 0
    for name, p in net.state_dict().items():
        a = p.detach().cpu().numpy().astype(np.float32)
        cname = "W_" + name.replace(".", "_")
        if a.ndim >= 2:
            s = max(float(np.abs(a).max()) / 127.0, 1e-8)
            L.append(f"/* {name} shape={list(a.shape)} */\n")
            L.append(c_array(cname, np.clip(np.round(a / s), -127, 127).astype(np.int8), "int8_t"))
            L.append(f"static const float {cname}_SCALE = {s:.9g}f;\n")
            flash += a.size
        else:
            L.append(c_array(cname, a, "float")); flash += a.size * 4
    open(path, "w").write("".join(L))
    return flash


def main():
    net = EdgeChemNet(); net.load_state_dict(torch.load(f"{ARTIFACT}_weights.pt")); net.eval()
    ex = torch.zeros(1, MAX_LEN, dtype=torch.long); ex[0, :5] = 7

    ts = torch.jit.trace(net, ex, check_trace=False); ts.save(OUT[0])           # TorchScript
    try:                                                                         # ONNX
        torch.onnx.export(net, ex, OUT[1], input_names=["ids"],
                          output_names=["safety", "arm", "intent", "embedding", "topic"],
                          dynamic_axes={"ids": {0: "batch"}}, opset_version=17, dynamo=False)
    except TypeError:
        torch.onnx.export(net, ex, OUT[1], input_names=["ids"],
                          output_names=["safety", "arm", "intent", "embedding", "topic"],
                          dynamic_axes={"ids": {0: "batch"}}, opset_version=17)
    q = torch.ao.quantization.quantize_dynamic(net, {nn.Linear}, dtype=torch.qint8)  # INT8
    try:
        torch.jit.trace(q, ex, check_trace=False).save(OUT[2])
    except Exception:
        torch.save(q, OUT[2])
    flash = write_header(net, OUT[3])

    for f in OUT: print(f"{f:34s} {kb(f)}")
    print(f"C header weight payload (flash): ~{flash/1024:.0f} KB")
    assert os.path.getsize(OUT[2]) <= 1_000_000, "quantized model exceeds 1 MB"
    try:                                                                         # parity check
        import onnxruntime as ort
        s = ort.InferenceSession(OUT[1]); o = s.run(None, {"ids": ex.numpy()})
        with torch.no_grad(): r = net(ex)
        print("ONNX vs torch max |diff|:", float(np.abs(o[4] - r[4].numpy()).max()))
    except ImportError:
        print("onnxruntime not installed: skipped ONNX parity check")


if __name__ == "__main__":
    main()
